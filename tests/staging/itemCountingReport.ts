/**
 * Builds staging-results-item-counting.md from the gate's current state.
 * Pure (no I/O) so it can be rebuilt after every step and unit-tested.
 *
 * The runner rewrites the report after every SQL statement, every measured
 * case and every heartbeat. A report written mid-run always ends with a
 * FAILED status line, so a stopped or killed run can never read as complete,
 * while everything finished up to that point is kept.
 */
import { measureTable, STAGING_REF } from "./measure-item-counting";
import {
  checkItemCountingEvidence,
  overTarget,
  statusLine,
  type FileRun,
  type MeasureOutcome,
  type StatementResult,
} from "./itemCountingEvidence";

const MAX_ROWS_SHOWN = 500;

export interface GateState {
  startedAt: string;
  revision: string;
  runs: FileRun[];
  measures: { owner: MeasureOutcome; manager: MeasureOutcome };
  /** Step now running, e.g. "measuring as owner · AU 3 months (busy) · run 1/3". Null when finished. */
  current: string | null;
  /** Latest progress line for the current step (heartbeat). */
  lastProgress: string | null;
  /** Set when the run was interrupted (Ctrl+C / terminate). */
  stopped: string | null;
  /** Settings/connection error that ended the run early. */
  fatal: string | null;
  finishedAt: string | null;
}

export interface GateReport {
  markdown: string;
  problems: string[];
  slow: string[];
  status: string;
}

function cell(v: unknown): string {
  if (v === null || v === undefined) return "∅";
  const s = v instanceof Date ? v.toISOString() : typeof v === "object" ? JSON.stringify(v) : String(v);
  return s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

export function resultMarkdown(r: StatementResult): string {
  const head = `#### Statement ${r.index} · line ${r.line} · \`${r.label.replace(/`/g, "'")}\`\n\n` +
    `command: ${r.command ?? "–"} · rows: ${r.rowCount ?? r.rows.length} · ${r.ms} ms` +
    (r.error ? `\n\n**ERROR:** ${r.error}` : "") +
    (r.notices.length ? `\n\nnotices: ${r.notices.join("; ")}` : "");
  if (r.command === "EXPLAIN") {
    return `${head}\n\n\`\`\`\n${r.rows.map((row) => String(Object.values(row)[0])).join("\n")}\n\`\`\``;
  }
  if (!r.rows.length || !r.fields.length) return head;
  const shown = r.rows.slice(0, MAX_ROWS_SHOWN);
  const table = [
    `| ${r.fields.join(" | ")} |`,
    `| ${r.fields.map(() => "---").join(" | ")} |`,
    ...shown.map((row) => `| ${r.fields.map((f) => cell(row[f])).join(" | ")} |`),
  ].join("\n");
  const more = r.rows.length > shown.length ? `\n\n(${r.rows.length - shown.length} more rows not shown)` : "";
  return `${head}\n\n${table}${more}`;
}

/** Problems for the STATUS line: interruption / unfinished run first, then every evidence gap. */
export function gateProblems(state: GateState): string[] {
  const first: string[] = [];
  if (state.stopped) first.push(`stopped during ${state.current ?? "the run"} (${state.stopped}); partial evidence only`);
  else if (state.current) first.push(`run not finished: ${state.current} (still running, or stopped without a final report)`);
  if (state.fatal) first.push(state.fatal);
  return [...first, ...checkItemCountingEvidence(state.runs, state.measures)];
}

export function buildReport(state: GateState): GateReport {
  const problems = gateProblems(state);
  const slow = overTarget(state.measures);
  const status = statusLine(problems);
  const unfinished = state.current !== null || state.stopped !== null;

  const parts: string[] = [
    "# item-counting · staging gate results",
    "",
    `- project: ${STAGING_REF} (staging)`,
    `- code revision: ${state.revision}`,
    `- started: ${state.startedAt} · ${state.finishedAt ? `finished: ${state.finishedAt}` : "not finished"}`,
    "- generated by `npm run staging:item-counting`; credentials are not recorded",
    "- this file is rewritten after every step, so finished evidence survives a stop",
  ];
  if (unfinished) {
    parts.push(
      "",
      "## Progress",
      "",
      `- ${state.stopped ? "stopped during" : "now running"}: ${state.current ?? "–"}`,
      `- last progress: ${state.lastProgress ?? "–"}`,
    );
  }
  for (const run of state.runs) {
    parts.push("", `## ${run.file} (${run.results.length} of ${run.statements} statements)`, "");
    for (const r of run.results) parts.push(resultMarkdown(r), "");
  }
  for (const who of ["owner", "manager"] as const) {
    const m = state.measures[who];
    parts.push("", `## Loader measurements as ${who}`, "");
    if (!m) parts.push("Not run.");
    else if ("error" in m) parts.push(`**FAILED:** ${m.error}`);
    else parts.push(measureTable(m), ...(m.rows.length < 6 ? ["", `(${m.rows.length} of 6 cases finished)`] : []));
  }
  parts.push("", "## Checks", "");
  parts.push(problems.length ? problems.map((p) => `- MISSING/WRONG: ${p}`).join("\n") : "- Every expected result is present and non-empty.");
  parts.push("", "## Latency targets (one day ≤ 2,000 ms, three months ≤ 10,000 ms)", "");
  if (slow.length) {
    parts.push(slow.map((s) => `- OVER TARGET: ${s}`).join("\n"));
    if (!problems.length) {
      parts.push("", "Evidence is complete but targets were missed: the coder records this as an Open question in the plan and does not start Task 5.");
    }
  } else {
    parts.push(problems.length ? "- No finished case missed its target so far; evidence is incomplete." : "- All cases within target.");
  }
  parts.push("", status, "");
  return { markdown: parts.join("\n"), problems, slow, status };
}

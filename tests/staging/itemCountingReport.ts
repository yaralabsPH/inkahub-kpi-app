/**
 * Builds staging-results-item-counting.md from the gate's current state.
 * Pure (no I/O) so it can be rebuilt after every step and unit-tested.
 *
 * The runner rewrites the report after every SQL statement, every measured
 * run and every heartbeat. A report written mid-run always ends with a
 * FAILED status line, so a stopped or killed run can never read as complete,
 * while everything finished up to that point is kept.
 */
import { measureTable, STAGING_REF } from "./measure-item-counting";
import {
  checkItemCountingEvidence,
  MANAGER_PHASES,
  overTarget,
  statusLine,
  type FileRun,
  type GateMode,
  type ManagerPhase,
  type MeasureOutcome,
  type PhaseRecord,
  type StatementResult,
} from "./itemCountingEvidence";
import { parityArtifactHash, type ClaimsSource, type ParityArtifact } from "./itemCountingPolicyParity";

const MAX_ROWS_SHOWN = 500;

export interface GateState {
  startedAt: string;
  revision: string;
  mode: GateMode;
  runs: FileRun[];
  measures: { owner: MeasureOutcome; manager: MeasureOutcome };
  /** This run's manager membership phase (null until known, or if memberships are unexpected). */
  managerPhase: ManagerPhase | null;
  /** Manager phases recorded by earlier runs and, once finished, this one. */
  phaseRecords: PhaseRecord[];
  /** Real-session claims (sizes/shapes only, never values) per role, from this run's sign-ins. */
  claimsSources: Record<string, ClaimsSource>;
  /** The policy parity artifact (before/after 0036), if any. */
  parity: ParityArtifact | null;
  /** Step now running, e.g. "measuring as owner · AU 3 months (busy) · run 1/3". Null when finished. */
  current: string | null;
  /** Latest progress line for the current step (heartbeat). */
  lastProgress: string | null;
  /** Set when the run was interrupted (Ctrl+C / terminate). */
  stopped: string | null;
  /** Settings/connection error that ended the run early. */
  fatal: string | null;
  finishedAt: string | null;
}

export interface GateReport {
  markdown: string;
  problems: string[];
  slow: string[];
  status: string;
}

function cell(v: unknown): string {
  if (v === null || v === undefined) return "∅";
  const s = v instanceof Date ? v.toISOString() : typeof v === "object" ? JSON.stringify(v) : String(v);
  return s.replace(/\|/g, "\\|").replace(/\r?\n/g, " ");
}

export function resultMarkdown(r: StatementResult): string {
  const head = `#### Statement ${r.index} · line ${r.line} · \`${r.label.replace(/`/g, "'")}\`\n\n` +
    `command: ${r.command ?? "–"} · rows: ${r.rowCount ?? r.rows.length} · ${r.ms} ms` +
    (r.error ? `\n\n**ERROR:** ${r.error}` : "") +
    (r.notices.length ? `\n\nnotices: ${r.notices.join("; ")}` : "");
  if (r.command === "EXPLAIN") {
    return `${head}\n\n\`\`\`\n${r.rows.map((row) => String(Object.values(row)[0])).join("\n")}\n\`\`\``;
  }
  if (!r.rows.length || !r.fields.length) return head;
  const shown = r.rows.slice(0, MAX_ROWS_SHOWN);
  const table = [
    `| ${r.fields.join(" | ")} |`,
    `| ${r.fields.map(() => "---").join(" | ")} |`,
    ...shown.map((row) => `| ${r.fields.map((f) => cell(row[f])).join(" | ")} |`),
  ].join("\n");
  const more = r.rows.length > shown.length ? `\n\n(${r.rows.length - shown.length} more rows not shown)` : "";
  return `${head}\n\n${table}${more}`;
}

/** Problems for the STATUS line: interruption / unfinished run first, then every evidence gap or miss. */
export function gateProblems(state: GateState): string[] {
  const first: string[] = [];
  if (state.stopped) first.push(`stopped during ${state.current ?? "the run"} (${state.stopped}); partial evidence only`);
  else if (state.current) first.push(`run not finished: ${state.current} (still running, or stopped without a final report)`);
  if (state.fatal) first.push(state.fatal);
  return [
    ...first,
    ...checkItemCountingEvidence({
      mode: state.mode,
      runs: state.runs,
      measures: state.measures,
      managerPhase: state.managerPhase,
      phaseRecords: state.phaseRecords,
      extras: { claimsSources: state.claimsSources, parity: state.parity },
    }),
  ];
}

export function buildReport(state: GateState): GateReport {
  const problems = gateProblems(state);
  const slow = overTarget(state.measures);
  const status = statusLine(problems);
  const unfinished = state.current !== null || state.stopped !== null;

  const parts: string[] = [
    "# item-counting · staging gate results",
    "",
    `- project: ${STAGING_REF} (staging)`,
    `- code revision: ${state.revision}`,
    `- started: ${state.startedAt} · ${state.finishedAt ? `finished: ${state.finishedAt}` : "not finished"}`,
    `- mode: ${state.mode} · manager phase this run: ${state.managerPhase ?? "not known yet"}`,
    "- generated by `npm run staging:item-counting`; credentials are not recorded",
    "- this file is rewritten after every step, so finished evidence survives a stop",
  ];
  if (unfinished) {
    parts.push(
      "",
      "## Progress",
      "",
      `- ${state.stopped ? "stopped during" : "now running"}: ${state.current ?? "–"}`,
      `- last progress: ${state.lastProgress ?? "–"}`,
    );
  }
  for (const run of state.runs) {
    parts.push("", `## ${run.file} (${run.results.length} of ${run.statements} statements)`, "");
    for (const r of run.results) parts.push(resultMarkdown(r), "");
  }
  for (const who of ["owner", "manager"] as const) {
    const m = state.measures[who];
    parts.push("", `## Loader measurements as ${who}`, "");
    if (!m) parts.push("Not run.");
    else if ("error" in m) parts.push(`**FAILED:** ${m.error}`);
    else parts.push(measureTable(m), ...(m.rows.length < 6 ? ["", `(${m.rows.length} of 6 cases finished)`] : []));
  }
  parts.push("", "## Real-session claims (sizes only; values are never recorded)", "", "| Role | Bytes | Problems |", "|---|---:|---|");
  for (const [role, c] of Object.entries(state.claimsSources)) parts.push(`| ${role} | ${c.bytes} | ${c.problems.length ? cell(c.problems.join("; ")) : "none"} |`);
  if (!Object.keys(state.claimsSources).length) parts.push("| – | – | no sessions signed in |");
  parts.push("", "## Policy parity (0036)", "");
  const cases = state.parity?.cases;
  if (!state.parity) parts.push("- No parity artifact.");
  else parts.push(`- parity artifact hash: ${parityArtifactHash(state.parity)}`);
  parts.push("", "### Four-case acceptance (in-transaction policy restore)", "");
  if (!cases) parts.push("- Not collected: run `--policy-parity=cases`.");
  else {
    parts.push(
      `- collection ${cases.collectionId} at ${cases.capturedAt} · restoration ${cases.restoration ? (cases.restoration.passed ? "passed" : "FAILED") : "not checked"}${cases.problems.length ? ` · FAILED: ${cell(cases.problems[0])}` : ""}`,
      "", "| Case | Policies restored pre-0036 → 0036 | Result |", "|---|---|---|",
    );
    for (const c of cases.comparisons) parts.push(`| ${c.case} | ${c.beforeHash.slice(0, 12)} → ${c.afterHash.slice(0, 12)} | ${c.problems.length ? `FAILED: ${cell(c.problems[0])}` : "identical visibility"} |`);
  }
  parts.push("", "### History (cannot certify on its own)", "");
  if (!state.parity?.comparisons.length) parts.push("- No before/after comparison.");
  else {
    parts.push("| Arrangement | Compared | Policies before → after | Result |", "|---|---|---|---|");
    for (const c of state.parity.comparisons) {
      parts.push(`| ${c.arrangement} | ${c.comparedAt} | ${c.beforeHash.slice(0, 12)} → ${c.afterHash.slice(0, 12)} | ${c.problems.length ? `FAILED: ${cell(c.problems[0])}` : "identical visibility"} |`);
    }
  }
  parts.push("", "## Manager membership phases", "", "| Phase | Recorded | Code | Result |", "|---|---|---|---|");
  for (const phase of MANAGER_PHASES) {
    const r = [...state.phaseRecords].reverse().find((x) => x.phase === phase);
    parts.push(r
      ? `| ${phase} | ${r.finishedAt} | ${r.revision} | ${r.problems.length ? `FAILED: ${cell(r.problems[0])}` : "passed"} |`
      : `| ${phase} | – | – | not recorded |`);
  }
  parts.push("", "## Checks", "");
  parts.push(problems.length ? problems.map((p) => `- MISSING/WRONG: ${p}`).join("\n") : "- Every expected result is present, correct and within target.");
  parts.push("", "## Latency targets (median paired total: one day ≤ 2,000 ms, three months ≤ 10,000 ms)", "");
  if (slow.length) {
    parts.push(slow.map((s) => `- OVER TARGET: ${s}`).join("\n"));
    parts.push("", "A missed target fails the gate: the coder records the measured bottleneck as an Open question for CJ and does not start Task 5.");
  } else {
    parts.push(problems.length ? "- No finished case missed its target so far." : "- All cases within target.");
  }
  parts.push("", status, "");
  return { markdown: parts.join("\n"), problems, slow, status };
}
